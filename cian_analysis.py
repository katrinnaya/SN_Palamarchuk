# Функция для получения списка объявлений с поисковой выдачи
def get_offers_list(page=1):
    """Получает список объявлений с поисковой выдачи Циан"""
    url = f"https://www.cian.ru/cat.php?deal_type=sale&engine_version=2&offer_type=flat&p={page}&region=1"

    try:
        response = requests.get(url, headers=get_headers(), timeout=10)
        response.raise_for_status()

        soup = BeautifulSoup(response.text, 'html.parser')
        offers = []

        # Ищем карточки объявлений
        offer_cards = soup.find_all('article', {'data-name': 'CardComponent'})

        for card in offer_cards:
            try:
                # Извлекаем ID объявления
                link_elem = card.find('a', href=re.compile(r'/sale/flat/\d+/'))
                if not link_elem:
                    continue

                href = link_elem.get('href', '')
                offer_id = re.search(r'/sale/flat/(\d+)/', href)
                if offer_id:
                    offer_id = offer_id.group(1)

                    # Основная информация
                    title_elem = card.find('span', {'data-mark': 'OfferTitle'})
                    price_elem = card.find('span', {'data-mark': 'MainPrice'})

                    title = title_elem.text.strip() if title_elem else ''
                    price = price_elem.text.strip() if price_elem else ''

                    # Адрес
                    address_elem = card.find('a', {'data-name': 'AddressItem'})
                    address = address_elem.text.strip() if address_elem else ''

                    offers.append({
                        'id': offer_id,
                        'title': title,
                        'price': price,
                        'address': address,
                        'url': f"https://www.cian.ru/sale/flat/{offer_id}/"
                    })

            except Exception as e:
                print(f"Ошибка парсинга карточки: {e}")
                continue

        return offers

    except Exception as e:
        print(f"Ошибка получения страницы {page}: {e}")
        return []

# Функция для парсинга детальной информации
def parse_property_info(text):
    result = {}

    # Общая площадь
    total_match = re.search(r'Общая\s+площадь\s*([\d,]+)\s*м²', text)
    if total_match:
        result['total_area'] = total_match.group(1).replace(',', '.')

    # Площадь кухни
    kitchen_match = re.search(r'Площадь\s+кухни\s*([\d,]+)\s*м²', text)
    if kitchen_match:
        result['kitchen_area'] = kitchen_match.group(1).replace(',', '.')

    # Жилая площадь
    living_match = re.search(r'Жилая\s+площадь\s*([\d,]+)\s*м²', text)
    if living_match:
        result['living_area'] = living_match.group(1).replace(',', '.')

    # Этаж
    floor_match = re.search(r'Этаж\s*(\d+)\s*из\s*(\d+)', text)
    if floor_match:
        result['floor'] = floor_match.group(1)
        result['total_floors'] = floor_match.group(2)

    # Год постройки
    year_match = re.search(r'Год\s+постройки\s*(\d+)', text)
    if year_match:
        result['build_year'] = year_match.group(1)

    # Количество комнат
    rooms_match = re.search(r'(\d+)-?комнат', text.lower())
    if rooms_match:
        result['rooms'] = rooms_match.group(1)
    elif 'студия' in text.lower():
        result['rooms'] = '0'

    # Тип дома
    if 'панел' in text.lower():
        result['house_type'] = 'панельный'
    elif 'монолит' in text.lower():
        result['house_type'] = 'монолитный'
    elif 'кирпич' in text.lower():
        result['house_type'] = 'кирпичный'
    elif 'блоч' in text.lower():
        result['house_type'] = 'блочный'
    elif 'дерев' in text.lower():
        result['house_type'] = 'деревянный'

    return result

# Функция для парсинга детальной страницы объявления
def parse_offer_detail(offer_id):
    """Парсит детальную информацию об объявлении"""
    url = f'https://www.cian.ru/sale/flat/{offer_id}/'

    try:
        response = requests.get(url, headers=get_headers(), timeout=10)
        response.raise_for_status()

        soup = BeautifulSoup(response.text, 'html.parser')

        # Адрес
        address_elem = soup.find('div', {'data-testid': 'object-address'})
        address = address_elem.text.strip() if address_elem else ''

        # Метро
        metro_items = soup.find_all('a', href=re.compile(r'/metro/'))
        stations = []
        for metro in metro_items:
            station_text = metro.text.strip()
            if station_text and 'метро' in station_text.lower():
                stations.append(station_text)

        # Цена
        price_elem = soup.find('div', {'data-testid': 'price-amount'})
        price = price_elem.text.strip() if price_elem else ''

        # Характеристики
        features = {}
        feature_elems = soup.find_all('div', class_=re.compile(r'feature'))

        for elem in feature_elems:
            text = elem.text.strip().lower()
            if 'общая' in text and 'м²' in text:
                area_match = re.search(r'(\d+[,.]?\d*)\s*м²', text)
                if area_match:
                    features['total_area'] = area_match.group(1).replace(',', '.')
            elif 'кухня' in text and 'м²' in text:
                area_match = re.search(r'(\d+[,.]?\d*)\s*м²', text)
                if area_match:
                    features['kitchen_area'] = area_match.group(1).replace(',', '.')
            elif 'этаж' in text:
                floor_match = re.search(r'(\d+)\s*из\s*(\d+)', text)
                if floor_match:
                    features['floor'] = floor_match.group(1)
                    features['total_floors'] = floor_match.group(2)
            elif 'комнат' in text:
                rooms_match = re.search(r'(\d+)\s*комнат', text)
                if rooms_match:
                    features['rooms'] = rooms_match.group(1)
                elif 'студия' in text:
                    features['rooms'] = '0'

        # Если не нашли через features, пробуем альтернативный способ
        if not features:
            factoid_text = soup.get_text()
            features = parse_property_info(factoid_text)

        # Описание
        desc_elem = soup.find('div', {'data-testid': 'object-description'})
        description = desc_elem.text.strip() if desc_elem else ''

        return {
            'id': offer_id,
            'address': address,
            'stations': stations,
            'price': price,
            'features': features,
            'description': description
        }

    except Exception as e:
        print(f"Ошибка парсинга объявления {offer_id}: {e}")
        return None

