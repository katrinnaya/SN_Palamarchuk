# Этап 4. Генерация признаков (Feature Engineering)

import pandas as pd
import numpy as np

# Загрузка данных
df = pd.read_csv('cian_clean.csv')

print("ЭТАП 4: ГЕНЕРАЦИЯ ПРИЗНАКОВ")
print("=" * 40)

# Создаем копию
df_simple = df.copy()

print(f"Исходные колонки: {list(df_simple.columns)}")

# 1. ЦЕНА ЗА КВАДРАТНЫЙ МЕТР
df_simple['price_per_m2'] = df_simple['price'] / df_simple['total_area']

# 2. ПРИЗНАК НОВОСТРОЙКИ
df_simple['is_new_building'] = (df_simple['year_built'] >= 2010).astype(int)

# 3. ВОЗРАСТ ЗДАНИЯ
df_simple['building_age'] = 2025 - df_simple['year_built']

# 4. КОЭФФИЦИЕНТ ЭТАЖА
df_simple['floor_ratio'] = df_simple['floor'] / df_simple['floors_total']

# 5. РАССТОЯНИЕ ДО ЦЕНТРА (простая версия)
def simple_center_distance(district):
    if district in ['Тверской', 'Мещанский']:
        return 'center'
    else:
        return 'not_center'

df_simple['center_distance'] = df_simple['district'].apply(simple_center_distance)

print(f"\nСгенерировано 5 новых признаков:")
print("1. price_per_m2 - цена за м²")
print("2. is_new_building - новостройка (0/1)")
print("3. building_age - возраст здания")
print("4. floor_ratio - коэффициент этажа")
print("5. center_distance - расстояние до центра")

# Проверка новых признаков
print(f"\nПроверка новых признаков:")
print(df_simple[['price_per_m2', 'is_new_building', 'building_age', 'floor_ratio', 'center_distance']].head())

# Сохраняем результат
df_simple.to_csv('cian_simple_features.csv', index=False, encoding='utf-8')
print(f"\n✅ Данные сохранены в 'cian_simple_features.csv'")
print(f"✅ Итоговое количество колонок: {len(df_simple.columns)}")