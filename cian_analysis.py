class CianParser:
    def __init__(self):
        self.session = requests.Session()
        self.session.headers = {
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
            'Accept-Language': 'ru'
        }
        self.result = []
        # Добавляем заголовки
        self.result.append(ParseResults(
            offer_id='offer_id',
            title='title',
            address='address',
            district='district',
            price='price',
            total_area='total_area',
            rooms='rooms',
            floor='floor',
            floors_total='floors_total',
            house_type='house_type',
            year_built='year_built',
            description='description'
        ))

    def load_page(self, page=1):
        """Загрузка страницы с объявлениями"""
        url = f"https://www.cian.ru/cat.php?deal_type=sale&engine_version=2&offer_type=flat&p={page}&region=1"
        try:
            res = self.session.get(url=url, timeout=10)
            res.raise_for_status()
            return res.text
        except Exception as e:
            print(f"Ошибка загрузки страницы {page}: {e}")
            return None

    def parse_page(self, html: str):
        """Парсинг списка объявлений на странице"""
        if not html:
            return

        soup = BeautifulSoup(html, 'lxml')
        offers = soup.select("article[data-name='CardComponent']")

        print(f"Найдено объявлений на странице: {len(offers)}")

        for block in offers:
            try:
                self.parse_block(block=block)
                time.sleep(0.5)  # Задержка между запросами
            except Exception as e:
                print(f"Ошибка парсинга блока: {e}")
                continue

    def parse_block(self, block):
        """Парсинг отдельного объявления из списка"""
        # ID объявления
        link_elem = block.select("a[data-name='Link']")[0]
        link = link_elem.get('href', '')
        offer_id = re.search(r'/(\d+)/', link)
        offer_id = offer_id.group(1) if offer_id else ''

        # Заголовок
        title_elem = block.select("span[data-mark='OfferTitle']")
        title = title_elem[0].text.strip() if title_elem else ''

        # Адрес и район
        address_elem = block.select("a[data-name='AddressItem']")
        address_full = address_elem[0].text.strip() if address_elem else ''

        # Разделяем адрес и район
        address_parts = [part.strip() for part in address_full.split(',')]
        address = address_parts[-1] if address_parts else ''
        district = address_parts[-2] if len(address_parts) > 1 else ''

        # Цена
        price_elem = block.select("span[data-mark='MainPrice']")
        price_text = price_elem[0].text.strip() if price_elem else ''
        price = re.sub(r'[^\d]', '', price_text) if price_text else '0'

        # Основные характеристики из заголовка
        rooms, total_area, floor_info = self.parse_title_info(title)

        # Этажи
        floor, floors_total = self.parse_floor_info(floor_info)

        # Загружаем детальную страницу для дополнительной информации
        house_type, year_built, description = self.parse_detail_page(offer_id)

        # Добавляем результат
        self.result.append(ParseResults(
            offer_id=offer_id,
            title=title,
            address=address,
            district=district,
            price=price,
            total_area=total_area,
            rooms=rooms,
            floor=floor,
            floors_total=floors_total,
            house_type=house_type,
            year_built=year_built,
            description=description
        ))

        print(f"Обработано объявление {offer_id}: {title}")

    def parse_title_info(self, title):
        """Парсинг информации из заголовка"""
        rooms = 0
        total_area = 0
        floor_info = ""

        # Количество комнат
        if 'студия' in title.lower():
            rooms = 0
        else:
            rooms_match = re.search(r'(\d+)-комн', title.lower())
            rooms = rooms_match.group(1) if rooms_match else ''

        # Площадь
        area_match = re.search(r'(\d+[,.]?\d*)\s*м²', title.lower())
        total_area = area_match.group(1).replace(',', '.') if area_match else ''

        # Этажи
        floor_match = re.search(r'(\d+)\s*/\s*(\d+)\s*эт', title.lower())
        if floor_match:
            floor_info = f"{floor_match.group(1)}/{floor_match.group(2)}"

        return rooms, total_area, floor_info

    def parse_floor_info(self, floor_info):
        """Парсинг информации о этажах"""
        if floor_info and '/' in floor_info:
            parts = floor_info.split('/')
            return parts[0], parts[1]
        return '', ''

    def parse_detail_page(self, offer_id):
        """Парсинг детальной страницы объявления"""
        house_type = ''
        year_built = ''
        description = ''

        try:
            url = f"https://www.cian.ru/sale/flat/{offer_id}/"
            res = self.session.get(url=url, timeout=10)
            res.raise_for_status()

            soup = BeautifulSoup(res.text, 'lxml')

            # Тип дома
            house_elems = soup.find_all('div', string=re.compile(r'Тип дома', re.IGNORECASE))
            for elem in house_elems:
                next_elem = elem.find_next_sibling('div')
                if next_elem:
                    house_type = next_elem.text.strip()
                    break

            # Год постройки
            year_elems = soup.find_all('div', string=re.compile(r'Год постройки', re.IGNORECASE))
            for elem in year_elems:
                next_elem = elem.find_next_sibling('div')
                if next_elem:
                    year_text = next_elem.text.strip()
                    year_match = re.search(r'\d{4}', year_text)
                    year_built = year_match.group() if year_match else ''
                    break

            # Описание
            desc_elem = soup.find('div', {'data-name': 'Description'})
            if desc_elem:
                description = desc_elem.text.strip()[:200]  # Ограничиваем длину

        except Exception as e:
            print(f"Ошибка парсинга детальной страницы {offer_id}: {e}")

        return house_type, year_built, description

    def save_results(self):
        """Сохранение результатов в CSV"""
        filename = "cian_raw.csv"
        with open(filename, "w", newline='', encoding='utf-8') as f:
            writer = csv.writer(f, quoting=csv.QUOTE_MINIMAL)
            for item in self.result:
                writer.writerow(item)
        print(f"Результаты сохранены в {filename}")

    def run(self):
        """Основной метод запуска парсера"""
        print("Начинаем парсинг Циан...")

        for page in range(1, 4):  # Первые 3 страницы
            print(f"Парсинг страницы {page}...")
            html = self.load_page(page=page)
            if html:
                self.parse_page(html=html)
            time.sleep(1)  # Задержка между страницами

        print(f"Парсинг завершен. Собрано {len(self.result) - 1} объявлений")

if __name__ == '__main__':
    parser = CianParser()
    parser.run()
    parser.save_results()

